// fa_render — offline render, introspection and benchmarks for fluent_audio.
//
//   fa_render <sound.yaml> <look|-> in.wav out.wav [--param name=v]... [--block N] [--tail S] [--no-trim]
//   fa_render --list [--markdown]            every node type (and built-in macro) with its params
//   fa_render --describe <sound.yaml>        compiled structure, param names, digest, memory
//   fa_render --loudness <file.wav>          integrated loudness (BS.1770)
//   fa_render --bench <sound.yaml> [sec]     µs per 128-frame block per preset, and while crossfading
#include <algorithm>
#include <chrono>
#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <string>
#include <vector>

#include "fluent_audio/engine.hpp"
#include "fluent_audio/yaml.hpp"
#include "loudness.hpp"
#include "wav.hpp"

using namespace fluent_audio;

namespace fluent_audio {
extern const char* const kBuiltinMacros[][2];
extern const int kBuiltinMacroCount;
}

static bool readText(const std::string& path, std::string& out) {
    FILE* f = std::fopen(path.c_str(), "rb");
    if (!f) return false;
    char b[8192];
    size_t n;
    while ((n = std::fread(b, 1, sizeof b, f)) > 0) out.append(b, n);
    std::fclose(f);
    return true;
}
static std::string dirOf(const std::string& p) {
    const size_t s = p.find_last_of('/');
    return s == std::string::npos ? "." : p.substr(0, s);
}
static int usage() {
    std::fprintf(stderr,
                 "usage: fa_render <sound.yaml> <look|-> in.wav out.wav [--param name=v]... [--block N] [--tail S] [--no-trim]\n"
                 "       fa_render --list [--markdown] | --describe <sound.yaml> | --loudness <wav> | --bench <sound.yaml> [sec]\n");
    return 2;
}

static std::unique_ptr<Engine> load(const std::string& path, double sr, int block) {
    std::string text, err;
    if (!readText(path, text)) { std::fprintf(stderr, "cannot read %s\n", path.c_str()); return nullptr; }
    Options o;
    o.sample_rate = sr;
    o.max_block = block;
    o.search_dir = dirOf(path);
    auto e = Engine::create(text, o, err);
    if (!e) std::fprintf(stderr, "%s\n", err.c_str());
    return e;
}

static int list(bool md) {
    if (md) std::printf("# fluent_audio nodes\n\n_Generated by `fa_render --list --markdown` from the node tables (src/nodes/) and macros/._\n\n");
    for (const NodeInfo* n : nodeRegistry()) {
        if (md) {
            std::printf("## `%s`\n\n%s  (~%d ops/sample)\n\n| param | unit | range | default | runtime | |\n|---|---|---|---|---|---|\n", n->name, n->help, n->cost);
            for (int i = 0; i < n->nparams; ++i) {
                const ParamSpec& p = n->params[i];
                std::string name = p.group ? std::string(p.group) + "[]." + p.name : p.name;
                std::printf("| %s | %s | %g … %g | %g | %s | %s%s%s |\n", name.c_str(), p.unit, p.min, p.max, p.def,
                            p.smooth == Smooth::kFixed ? "fixed" : "yes", p.help, p.choices ? " — " : "", p.choices ? p.choices : "");
            }
            std::printf("\n");
        } else {
            std::printf("%-12s %s\n", n->name, n->help);
            for (int i = 0; i < n->nparams; ++i) {
                const ParamSpec& p = n->params[i];
                std::printf("    %-14s %-4s [%g, %g] = %g%s  %s\n", p.name, p.unit, p.min, p.max, p.def,
                            p.smooth == Smooth::kFixed ? " (fixed)" : "", p.help);
            }
        }
    }
    for (int i = 0; i < kBuiltinMacroCount; ++i) {
        yaml::DiagnosticList dl;
        auto doc = yaml::parseYaml(kBuiltinMacros[i][1], dl);
        const auto* help = doc.find("help");
        if (md) {
            std::printf("## `%s` (macro, macros/%s.yaml)\n\n%s\n\n| param | default | range |\n|---|---|---|\n", kBuiltinMacros[i][0],
                        kBuiltinMacros[i][0], help ? help->scalar.c_str() : "");
            if (const auto* ps = doc.find("params"))
                for (const auto& e : ps->entries) {
                    const auto* d = e.value.find("default");
                    const auto* r = e.value.find("range");
                    std::printf("| %s | %s | %s … %s |\n", e.key.c_str(), d ? d->scalar.c_str() : "",
                                r && r->elements.size() == 2 ? r->elements[0].scalar.c_str() : "",
                                r && r->elements.size() == 2 ? r->elements[1].scalar.c_str() : "");
                }
            std::printf("\n");
        } else {
            std::printf("%-12s (macro) %s\n", kBuiltinMacros[i][0], help ? help->scalar.c_str() : "");
        }
    }
    return 0;
}

static int describe(const std::string& path) {
    auto e = load(path, 48000, 128);
    if (!e) return 1;
    std::printf("%sdigest %s  memory %.1f KB  latency %d samples\nparams (%d):\n", e->describe().c_str(), e->digest().c_str(),
                e->memoryBytes() / 1024.0, e->latencySamples(), e->paramCount());
    for (int i = 0; i < e->paramCount(); ++i) {
        const auto& h = e->param(i);
        std::printf("  %-44s %g  [%g, %g]%s\n", h.name.c_str(), h.value, h.min, h.max, h.runtime ? "" : " fixed");
    }
    return 0;
}

static int bench(const std::string& path, double secs) {
    auto e = load(path, 48000, 128);
    if (!e) return 1;
    const int blocks = static_cast<int>(secs * 48000 / 128);
    dsp::Rng rng(7);
    std::vector<float> input(static_cast<size_t>(blocks) * 128);
    float b0 = 0, b1 = 0;
    for (size_t i = 0; i < input.size(); ++i) {   // speech-like: pinkish noise in 120 ms bursts
        const float w = rng.uni();
        b0 = 0.99f * b0 + 0.1f * w;
        b1 = 0.6f * b1 + 0.4f * b0;
        input[i] = ((i / 5760) % 3 != 2) ? b1 * 0.5f : 0.0f;
    }
    auto run = [&](int preset, bool xfade) {
        std::vector<double> t(blocks);
        e->reset();
        e->selectIdx(preset);
        for (int b = 0; b < blocks; ++b) {
            if (xfade && b % 94 == 0) e->selectIdx((preset + b / 94) % e->presetCount());   // a switch every 0.25 s
            std::memcpy(e->in(0), &input[static_cast<size_t>(b) * 128], 128 * sizeof(float));
            const auto t0 = std::chrono::steady_clock::now();
            e->process(128);
            t[b] = std::chrono::duration<double, std::micro>(std::chrono::steady_clock::now() - t0).count();
        }
        std::sort(t.begin(), t.end());
        double mean = 0;
        for (double v : t) mean += v;
        mean /= blocks;
        std::printf("%-14s mean %6.1f µs  p99 %6.1f µs  max %6.1f µs   (%.2f%% of a 2.67 ms quantum, mean)\n",
                    xfade ? "(switching)" : e->presetName(preset).c_str(), mean, t[blocks * 99 / 100], t.back(), mean / 2666.7 * 100);
    };
    for (int p = 0; p < e->presetCount(); ++p) run(p, false);
    if (e->presetCount() > 1) run(0, true);
    std::printf("memory %.1f KB\n", e->memoryBytes() / 1024.0);
    return 0;
}

int main(int argc, char** argv) {
    if (argc < 2) return usage();
    const std::string a1 = argv[1];
    if (a1 == "--list") return list(argc > 2 && std::string(argv[2]) == "--markdown");
    if (a1 == "--describe" && argc > 2) return describe(argv[2]);
    if (a1 == "--bench" && argc > 2) return bench(argv[2], argc > 3 ? std::atof(argv[3]) : 10.0);
    if (a1 == "--loudness" && argc > 2) {
        fa_tools::Wav w;
        std::string err;
        if (!fa_tools::readWav(argv[2], w, err)) { std::fprintf(stderr, "%s\n", err.c_str()); return 1; }
        std::printf("%.2f LUFS\n", fa_tools::integratedLufs(w.ch, w.sr));
        return 0;
    }
    if (argc < 5) return usage();
    const std::string sound = argv[1], look = argv[2], inp = argv[3], outp = argv[4];
    int block = 128;
    double tail = 2.5;
    bool trim = true;
    std::vector<std::pair<std::string, float>> params;
    for (int i = 5; i < argc; ++i) {
        const std::string a = argv[i];
        if (a == "--block" && i + 1 < argc) block = std::atoi(argv[++i]);
        else if (a == "--tail" && i + 1 < argc) tail = std::atof(argv[++i]);
        else if (a == "--no-trim") trim = false;
        else if (a == "--param" && i + 1 < argc) {
            const std::string kv = argv[++i];
            const size_t eq = kv.find('=');
            if (eq == std::string::npos) return usage();
            params.push_back({kv.substr(0, eq), static_cast<float>(std::atof(kv.c_str() + eq + 1))});
        } else return usage();
    }
    fa_tools::Wav in;
    std::string err;
    if (!fa_tools::readWav(inp, in, err)) { std::fprintf(stderr, "%s\n", err.c_str()); return 1; }
    auto e = load(sound, in.sr, block);
    if (!e) return 1;
    if (look != "-" && !e->select(look)) { std::fprintf(stderr, "no preset/look '%s'\n", look.c_str()); return 1; }
    for (auto& [k, v] : params)
        if (!e->setParam(k, v)) { std::fprintf(stderr, "param %s: %s\n", k.c_str(), e->takeDiagnostics().c_str()); return 1; }
    const size_t n = in.frames() + static_cast<size_t>(tail * in.sr);
    fa_tools::Wav out;
    out.sr = in.sr;
    out.channels = 2;
    out.ch.assign(2, std::vector<float>(n));
    for (size_t pos = 0; pos < n; pos += block) {
        const int m = static_cast<int>(std::min<size_t>(block, n - pos));
        for (int c = 0; c < 2; ++c) {
            const auto& src = in.ch[std::min(c, in.channels - 1)];
            for (int i = 0; i < m; ++i) e->in(c)[i] = pos + i < src.size() ? src[pos + i] : 0.0f;
        }
        e->process(m);
        for (int i = 0; i < m; ++i) {
            out.ch[0][pos + i] = e->out(0)[i];
            out.ch[1][pos + i] = e->out(1)[i];
        }
    }
    if (trim) {
        size_t last = in.frames();
        for (size_t i = n; i-- > in.frames();)
            if (std::fabs(out.ch[0][i]) > 1e-4f || std::fabs(out.ch[1][i]) > 1e-4f) { last = i; break; }
        const size_t keep = std::min(n, last + static_cast<size_t>(0.1 * in.sr));
        out.ch[0].resize(keep);
        out.ch[1].resize(keep);
    }
    if (!fa_tools::writeWav(outp, out)) { std::fprintf(stderr, "cannot write %s\n", outp.c_str()); return 1; }
    if (e->diagnosticsCount()) std::fprintf(stderr, "diagnostics: %d\n", e->diagnosticsCount());
    return 0;
}
