#!/usr/bin/env python3
"""Embed macros/*.yaml into a C++ source (the built-in macros every build knows, native and wasm).

  python3 tools/embed_macros.py <out.cpp> macros/*.yaml
"""
import os
import sys


def main():
    out, files = sys.argv[1], sorted(sys.argv[2:])
    rows = []
    for f in files:
        name = os.path.splitext(os.path.basename(f))[0]
        text = open(f, encoding="utf-8").read()
        rows.append(f'    {{"{name}", R"__fa__({text})__fa__"}},')
    body = "\n".join(rows) if rows else '    {"", ""},'
    src = f"""// generated by tools/embed_macros.py from macros/*.yaml — do not edit
namespace fluent_audio {{
extern const char* const kBuiltinMacros[][2];
extern const int kBuiltinMacroCount;
const char* const kBuiltinMacros[][2] = {{
{body}
}};
const int kBuiltinMacroCount = {len(rows)};
}}  // namespace fluent_audio
"""
    old = open(out).read() if os.path.exists(out) else None
    if old != src:
        os.makedirs(os.path.dirname(out) or ".", exist_ok=True)
        open(out, "w").write(src)


if __name__ == "__main__":
    main()
